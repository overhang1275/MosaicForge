import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';
import { bundleSchema } from './schema.mjs';

const root = new URL('../../', import.meta.url);
const contracts = {
  'durable-job-request': 'jobs/v2/request',
  'durable-job-status': 'jobs/v2/status',
  'block-request': 'worker/v1/block-request',
  'block-response': 'worker/v1/block-response',
};
async function output(path, value) {
  const file = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (
      (await readFile(file, 'utf8').catch(() => '')).replaceAll(
        '\r\n',
        '\n',
      ) !== value
    )
      throw new Error(`Stale generated durable contract: ${path}`);
  } else {
    await mkdir(new URL('.', file), { recursive: true });
    await writeFile(file, value);
  }
}
for (const [name, path] of Object.entries(contracts)) {
  const bundled = bundleSchema('common', { $ref: `../../${path}.schema.json` });
  await output(
    `contracts/generated/java-resources/${name}.json`,
    JSON.stringify(bundled, null, 2) + '\n',
  );
}
const bundled = bundleSchema('common', {
  title: 'DurableMessage',
  oneOf: Object.values(contracts).map((path) => ({
    $ref: `../../${path}.schema.json`,
  })),
});
await output(
  'contracts/generated/typescript/durable.ts',
  (
    await compile(bundled, 'DurableMessage', {
      bannerComment:
        '/* Generated by scripts/contracts/durable-generate.mjs. */',
      style: { singleQuote: true, semi: true },
      $refOptions: { resolve: { file: false, http: false } },
    })
  ).replaceAll('\r\n', '\n'),
);
await output(
  'contracts/openapi/jobs-v2.json',
  JSON.stringify(
    {
      openapi: '3.1.0',
      info: {
        title: 'MosaicForge durable jobs — staged contract',
        version: '2',
      },
      'x-implemented': false,
      paths: {
        '/v2/jobs': {
          post: {
            parameters: [
              {
                in: 'header',
                name: 'Idempotency-Key',
                required: true,
                schema: {
                  type: 'string',
                  minLength: 16,
                  maxLength: 128,
                  pattern: '^[!-~]+$',
                },
              },
            ],
            requestBody: {
              required: true,
              content: {
                'application/json': {
                  schema: { $ref: '../jobs/v2/request.schema.json' },
                },
              },
            },
            responses: {
              202: {
                description:
                  'Durably accepted (route disabled until finalization is complete)',
                content: {
                  'application/json': {
                    schema: { $ref: '../jobs/v2/status.schema.json' },
                  },
                },
              },
            },
          },
        },
      },
    },
    null,
    2,
  ) + '\n',
);
