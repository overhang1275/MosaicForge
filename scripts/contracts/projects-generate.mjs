import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';
import { bundleSchema } from './schema.mjs';

export const names = [
  'create-request',
  'revision-request',
  'me-response',
  'project-response',
  'list-response',
  'revision-response',
  'error',
];
export const bundled = (name) =>
  bundleSchema('common', { $ref: `../../projects/v1/${name}.schema.json` });
const root = new URL('../../', import.meta.url);
async function output(path, value) {
  const target = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (
      (await readFile(target, 'utf8').catch(() => '')).replaceAll(
        '\r\n',
        '\n',
      ) !== value
    )
      throw new Error(`Generated project contract out of date: ${path}`);
  } else {
    await mkdir(new URL('.', target), { recursive: true });
    await writeFile(target, value);
  }
}
for (const name of names)
  await output(
    `contracts/generated/java-resources/projects-${name}.json`,
    JSON.stringify(bundled(name), null, 2) + '\n',
  );
const types = bundleSchema('common', {
  title: 'ProjectMessage',
  oneOf: names.map((name) => ({
    $ref: `../../projects/v1/${name}.schema.json`,
  })),
});
for (const name of Object.keys(types.definitions))
  if (name === 'SelectedPdfExportRequest')
    types.definitions[name] = {
      tsType: `import('./preview').SelectedPdfExportRequest`,
    };
await output(
  'contracts/generated/typescript/projects.ts',
  (
    await compile(types, 'ProjectMessage', {
      bannerComment:
        '/* Generated by scripts/contracts/projects-generate.mjs. */',
      style: { singleQuote: true, semi: true },
      $refOptions: { resolve: { file: false, http: false } },
    })
  ).replaceAll('\r\n', '\n'),
);
const routes = {
  '/v1/me': { get: ['me-response'] },
  '/v1/projects': {
    get: ['list-response'],
    post: ['project-response', 'create-request'],
  },
  '/v1/projects/{id}': { get: ['project-response'] },
  '/v1/projects/{id}/revisions': {
    post: ['revision-response', 'revision-request'],
  },
  '/v1/projects/{id}/revisions/{number}': { get: ['revision-response'] },
};
const schema = (name) => ({ $ref: `../projects/v1/${name}.schema.json` });
const content = (name) => ({ 'application/json': { schema: schema(name) } });
const paths = Object.fromEntries(
  Object.entries(routes).map(([path, methods]) => [
    path,
    Object.fromEntries(
      Object.entries(methods).map(([method, [response, request]]) => [
        method,
        {
          security: [{ serviceToken: [] }],
          ...(request
            ? { requestBody: { required: true, content: content(request) } }
            : {}),
          parameters: [
            ...(path.includes('{id}')
              ? [
                  {
                    in: 'path',
                    name: 'id',
                    required: true,
                    schema: { type: 'string', format: 'uuid' },
                  },
                ]
              : []),
            ...(path.includes('{number}')
              ? [
                  {
                    in: 'path',
                    name: 'number',
                    required: true,
                    schema: {
                      type: 'integer',
                      minimum: 1,
                      maximum: 2147483647,
                    },
                  },
                ]
              : []),
            ...(path === '/v1/projects' && method === 'get'
              ? [
                  {
                    in: 'query',
                    name: 'limit',
                    schema: {
                      type: 'integer',
                      minimum: 1,
                      maximum: 100,
                      default: 20,
                    },
                  },
                  {
                    in: 'query',
                    name: 'cursor',
                    schema: { type: 'string', format: 'uuid' },
                  },
                ]
              : []),
          ],
          responses: {
            [method === 'post' ? '201' : '200']: {
              description: 'Versioned project response',
              content: content(response),
            },
            ...Object.fromEntries(
              [400, 401, 404, 409, 413, 415, 502, 503, 504].map((status) => [
                status,
                {
                  description: 'Sanitized error',
                  content: {
                    'application/json': {
                      schema: { $ref: '../projects/v1/error.schema.json' },
                    },
                  },
                },
              ]),
            ),
          },
        },
      ]),
    ),
  ]),
);
await output(
  'contracts/openapi/projects-v1.json',
  JSON.stringify(
    {
      openapi: '3.1.0',
      info: { title: 'MosaicForge local projects', version: '1' },
      paths,
      components: {
        securitySchemes: { serviceToken: { type: 'http', scheme: 'bearer' } },
      },
    },
    null,
    2,
  ) + '\n',
);
